"""Build explicit, clean source and Typst Universe distributions (stdlib only)."""
import argparse
from pathlib import Path
import shutil
import tarfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
SOURCE_FILES = [
    "typst.toml", "mt2l.typ", "README.md", "LICENSE", "install.sh", "get.sh",
    "docs/universe.md", "docs/PUBLISHING.md",
    "scripts/convert.sh", "scripts/convert-test.sh", "scripts/dependencies.sh",
    "scripts/mt2l.lua", "scripts/mt2l/lexer.lua", "scripts/test_install.py",
    "scripts/package.py", "scripts/test_release.py", "tests/test_conversion.py",
    "templates/default.tex", "examples/main.typ", "examples/adapters.typ",
    "examples/package.typ", "examples/packages.typ",
]


def build(output):
    manifest = tomllib.loads((ROOT / "typst.toml").read_text())["package"]
    for field in ["name", "version", "entrypoint", "authors", "license", "description", "repository"]:
        if not manifest.get(field):
            raise ValueError(f"Missing required release metadata: {field}")
    if manifest["name"] != "mt2l" or manifest["license"] != "MIT":
        raise ValueError("Unexpected package identity or license")
    version = manifest["version"]
    if f'local version="{version}"' not in (ROOT / "get.sh").read_text():
        raise ValueError("Bootstrap version does not match typst.toml")
    for name in SOURCE_FILES:
        if not (ROOT / name).is_file():
            raise ValueError(f"Missing release file: {name}")
    if output.exists():
        if not (output / ".mt2l-release").is_file():
            raise ValueError(f"Refusing to replace unmanaged directory: {output}")
        shutil.rmtree(output)
    output.mkdir(parents=True)
    (output / ".mt2l-release").write_text("Generated by scripts/package.py\n")
    source = output / "source" / f"mt2l-{version}"
    for name in SOURCE_FILES:
        destination = source / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / name, destination)
    (source / ".gitignore").write_text("build/\n__pycache__/\n*.pyc\n")
    package = output / "packages" / "preview" / "mt2l" / version
    package.mkdir(parents=True)
    for name in ["typst.toml", "mt2l.typ", "LICENSE"]:
        shutil.copy2(ROOT / name, package / name)
    shutil.copy2(ROOT / "docs/universe.md", package / "README.md")
    for directory, archive in [
        (source, output / f"mt2l-{version}.tar.gz"),
        (package, output / f"mt2l-universe-{version}.tar.gz"),
    ]:
        with tarfile.open(archive, "w:gz") as bundle:
            bundle.add(directory, arcname=directory.relative_to(directory.parent if directory == source else output))
    return source, package


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "build/release")
    args = parser.parse_args()
    source, package = build(args.output.resolve())
    print(f"Clean GitHub source: {source}\nTypst Universe submission: {package}")
